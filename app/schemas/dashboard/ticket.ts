import { z } from "zod";
import { MESSAGES } from "~/constants/messages";

export const ticketSchema = z.object({
  name: z
    .string({ message: MESSAGES.VALIDATION.FIELDS.NAME.REQUIRED })
    .min(1, MESSAGES.VALIDATION.FIELDS.NAME.REQUIRED)
    .max(100, MESSAGES.VALIDATION.FIELDS.SUBJECT.MAX_LENGTH),

  email: z
    .email(MESSAGES.VALIDATION.FIELDS.EMAIL.INVALID)
    .nonempty(MESSAGES.VALIDATION.FIELDS.EMAIL.REQUIRED)
    .max(50, MESSAGES.VALIDATION.FIELDS.URL.MAX_LENGTH),

  phone: z
    .string()
    .regex(/^09\d{9}$/, { message: MESSAGES.VALIDATION.FIELDS.PHONE.INVALID }),

  subject: z
    .string({ message: MESSAGES.VALIDATION.FIELDS.SUBJECT.REQUIRED })
    .min(1, MESSAGES.VALIDATION.FIELDS.SUBJECT.REQUIRED)
    .max(100, MESSAGES.VALIDATION.FIELDS.SUBJECT.MAX_LENGTH),

  description: z
    .string({ message: MESSAGES.VALIDATION.FIELDS.DESCRIPTION.REQUIRED })
    .min(1, MESSAGES.VALIDATION.FIELDS.DESCRIPTION.REQUIRED)
    .max(1000, MESSAGES.VALIDATION.FIELDS.DESCRIPTION.MAX_LENGTH),
});
